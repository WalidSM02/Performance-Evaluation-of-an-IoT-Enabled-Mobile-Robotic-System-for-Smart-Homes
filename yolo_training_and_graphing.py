import os
import yaml
import shutil
import random
import pandas as pd
import matplotlib.pyplot as plt
from ultralytics import YOLO

# ==========================================
# 1. AUTO-SPLIT DATASET (75% Train, 25% Val)
# ==========================================
INPUT_DIR = 'input_images'
DATASET_DIR = 'my_dataset'

# The classes your model is learning to detect (Update these if needed)
CLASS_NAMES = ['tv', 'laptop', 'cell phone', 'microwave', 'light']

print("📁 Preparing and splitting dataset (75% Train / 25% Val)...")

# Create required YOLO folder structure
for split in ['train', 'val']:
    os.makedirs(os.path.join(DATASET_DIR, split, 'images'), exist_ok=True)
    os.makedirs(os.path.join(DATASET_DIR, split, 'labels'), exist_ok=True)

# Get all images from input_images folder
if not os.path.exists(INPUT_DIR):
    print(f"❌ Error: Folder '{INPUT_DIR}' not found. Please create it and add your images!")
    exit()

all_files = [f for f in os.listdir(INPUT_DIR) if f.lower().endswith(('.jpg', '.jpeg', '.png'))]
random.shuffle(all_files) # Shuffle to ensure random distribution

# Calculate 75% split index
split_index = int(len(all_files) * 0.75)
train_images = all_files[:split_index]
val_images = all_files[split_index:]

def copy_to_dataset(img_list, split_name):
    for img_name in img_list:
        # 1. Copy Image
        src_img = os.path.join(INPUT_DIR, img_name)
        dst_img = os.path.join(DATASET_DIR, split_name, 'images', img_name)
        shutil.copy(src_img, dst_img)
        
        # 2. Copy Label (.txt file) if it exists
        # YOLO REQUIRES these text files to know where the objects are!
        label_name = os.path.splitext(img_name)[0] + '.txt'
        src_label = os.path.join(INPUT_DIR, label_name)
        if os.path.exists(src_label):
            dst_label = os.path.join(DATASET_DIR, split_name, 'labels', label_name)
            shutil.copy(src_label, dst_label)

# Run the split
copy_to_dataset(train_images, 'train')
copy_to_dataset(val_images, 'val')

print(f"✅ Split Complete! {len(train_images)} Training images, {len(val_images)} Validation images.")

# We auto-generate the YAML file pointing to the new split folders
# Using absolute paths to ensure YOLO finds them on Windows
yaml_content = {
    'train': os.path.abspath(os.path.join(DATASET_DIR, 'train', 'images')),
    'val': os.path.abspath(os.path.join(DATASET_DIR, 'val', 'images')),
    'nc': len(CLASS_NAMES),
    'names': CLASS_NAMES
}

yaml_filename = 'my_5k_dataset.yaml'
with open(yaml_filename, 'w') as f:
    yaml.dump(yaml_content, f, default_flow_style=False)

print(f"✅ Auto-generated dataset config: {yaml_filename}")


# ==========================================
# 2. YOLO TRAINING EXECUTION
# ==========================================
# Windows requires training to be inside the __name__ == '__main__' block
if __name__ == '__main__':
    
    print("\n🚀 Initializing YOLOv8 Model...")
    # SPEED HACK #1: Change 'yolov8m.pt' to 'yolov8n.pt' (Nano) for hyper-fast training
    model = YOLO('yolov8n.pt') 

    print("\n⏳ Starting Training on 5k Images! This will take some time...")
    # project='paper_results' and name='yolo_run' ensures we know EXACTLY where the logs are saved
    results = model.train(
        data=yaml_filename,
        epochs=50,             
        # SPEED HACK #2: Lower image size from 640 to 416 (or 320)
        imgsz=416,             
        batch=16,              
        project='paper_results', 
        name='yolo_run',       
        workers=0,             
        device=0,
        # SPEED HACK #3: Load images into RAM so the GPU doesn't wait on the hard drive
        cache=True             
    )
    
    print("\n✅ Training Complete!")


    # ==========================================
    # 3. AUTO-GENERATE GRAPHS FROM REAL DATA
    # ==========================================
    print("\n📊 Locating real training logs to generate Epoch graphs...")
    
    # Because we set project and name above, we know exactly where the CSV is:
    results_csv_path = os.path.join('runs', 'detect', 'paper_results', 'yolo_run', 'results.csv')
    
    if os.path.exists(results_csv_path):
        # Read the real data generated by YOLO
        df = pd.read_csv(results_csv_path)
        
        # YOLO column names have hidden spaces (e.g., '       metrics/mAP50(B)'), so we clean them
        df.columns = df.columns.str.strip()
        
        # Extract Epochs, Loss, and Accuracy
        epochs = df['epoch']
        real_loss = df['train/box_loss']
        real_accuracy = df['metrics/mAP50(B)'] * 100 # Multiply by 100 to make it a percentage
        
        # --- Plotting ---
        plt.figure(figsize=(14, 6))

        # Graph 1: Loss
        plt.subplot(1, 2, 1)
        plt.plot(epochs, real_loss, label='YOLOv8 Real Loss (5k imgs)', color='blue', linewidth=2.5, marker='o', markersize=4)
        plt.title('Real Training Loss over Epochs', fontsize=14)
        plt.xlabel('Epochs', fontsize=12)
        plt.ylabel('Box Loss', fontsize=12)
        plt.grid(True, linestyle=':', alpha=0.7)
        plt.legend()

        # Graph 2: Accuracy (mAP50)
        plt.subplot(1, 2, 2)
        plt.plot(epochs, real_accuracy, label='YOLOv8 Real Accuracy (5k imgs)', color='green', linewidth=2.5, marker='o', markersize=4)
        plt.title('Real Training Accuracy (mAP50) over Epochs', fontsize=14)
        plt.xlabel('Epochs', fontsize=12)
        plt.ylabel('Accuracy (%)', fontsize=12)
        plt.ylim(0, 100)
        plt.grid(True, linestyle=':', alpha=0.7)
        plt.legend()

        # Save the graph for your paper
        graph_filename = 'Real_YOLO_Training_Graph.png'
        plt.tight_layout()
        plt.savefig(graph_filename, dpi=300)
        plt.show()
        
        print(f"🎉 Success! Your real graphs are saved as '{graph_filename}'")
        print(f"Your raw CSV data is located at: {results_csv_path}")
        
    else:
        print(f"❌ Could not find {results_csv_path}. Did the training finish successfully?")